CREATE TABLE note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    title VARCHAR(255),
    content JSONB,
    version BIGINT NOT NULL DEFAULT 0,
    inbox BOOLEAN NOT NULL DEFAULT FALSE,
    archived_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_note PRIMARY KEY (id),
    CONSTRAINT fk_note_users FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_note_user_lifecycle_updated
    ON note (user_id, deleted_at, archived_at, updated_at DESC, id DESC);

CREATE TABLE note_creation_request (
    user_id BIGINT NOT NULL,
    request_key UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    note_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_note_creation_request PRIMARY KEY (user_id, request_key),
    CONSTRAINT fk_note_creation_request_users FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_note_creation_request_note FOREIGN KEY (note_id) REFERENCES note (id) ON DELETE SET NULL
);
