CREATE TABLE task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    task_key VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description JSONB,
    priority_id SMALLINT CHECK (priority_id IN (1, 2, 3, 4)),
    due_date DATE,
    inbox BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_task PRIMARY KEY (id),
    CONSTRAINT fk_task_users FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_task_user_id_task_key UNIQUE (user_id, task_key)
);

CREATE INDEX idx_task_user_list ON task (user_id, deleted_at, created_at DESC, id DESC);

CREATE TABLE task_key_counter (
    user_id BIGINT NOT NULL,
    last_allocated BIGINT NOT NULL CHECK (last_allocated >= 1),
    CONSTRAINT pk_task_key_counter PRIMARY KEY (user_id),
    CONSTRAINT fk_task_key_counter_users FOREIGN KEY (user_id) REFERENCES users (id)
);
