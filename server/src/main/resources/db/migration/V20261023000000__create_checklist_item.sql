CREATE TABLE checklist_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    due_date DATE,
    completed_at TIMESTAMPTZ,
    position INTEGER NOT NULL,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_checklist_item PRIMARY KEY (id),
    CONSTRAINT fk_checklist_item_task FOREIGN KEY (task_id) REFERENCES task (id)
);

CREATE INDEX idx_checklist_item_task_active_position
    ON checklist_item (task_id, position, id)
    WHERE deleted_at IS NULL;
